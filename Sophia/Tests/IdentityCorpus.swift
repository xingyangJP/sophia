// =============================================================================
//  第一号のアダプタの学習データ —— 自己認識（`docs/ADAPTER_01.md`）
//
//  ## 何を焼くのか
//
//  **いま「私はSophiaです」と言えているのは、毎ターン system プロンプトを
//  送っているからである。** 実測で確定している（`777e991` / `make identityprobe`）:
//
//  | 条件 | ソフィアと名乗る | Qwen と名乗る |
//  |---|--:|--:|
//  | プロンプト無し | **0/9** | 9/9 |
//  | プロンプト有り（出荷状態） | **9/9** | 0/9 |
//
//  **名前は約97トークンが毎ターン作っていて、重みの中には無い。**
//  ここを重みへ移すと、**毎ターンの費用が 0 になり、利用者に残る枠が約4倍になる。**
//
//  ## ⚠ 焼くときは system プロンプトを外すこと
//
//  **`StyleTrainingCorpus.input` は `SophiaDefaults.systemPromptEnabled` を見て
//  system を足す。** 足したまま焼くと、学習するのは
//  **「system プロンプトがあるときに Sophia と名乗る」**であって、
//  **それはいま既にできていることである。**
//
//  > **`SOPHIA_SYSTEM_PROMPT=0` で焼くこと。**
//  > **これを間違えると、70分かけて「いまと同じ状態」を学習する。**
//
//  ## 書き方の規則（14.13b節の事故を繰り返さないため）
//
//  **前回の LoRA 実測で、様式と一緒に「短さ」が乗った**（平均 283字 → 74〜90字）。
//  学習データが短かったためである。**合格率だけを見ていたら気づけない。**
//
//  1. **短く書かない。** 出荷時に期待する応答の長さで書く
//  2. **system プロンプトの本文を写さない。** 同じ内容を、多様な言い方で
//  3. **基盤モデルについて偽らない**（FR-23）。訊かれたら
//     「ローカルで動くオープンなモデルの上に構築されている」と答える。
//     **「Qwen ではない」とは言わない** ── それは嘘になる
//  4. **名乗り以外の話題を混ぜない。** 混ぜると、何が効いたのか分からなくなる
// =============================================================================

